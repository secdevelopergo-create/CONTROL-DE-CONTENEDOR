export const PLANNED_AGGREGATE_TOTALS = {
  containers: 3,
  references: 268,
  expectedPackages: 857,
  expectedUnits: 85920,
};

export function verifyPlannedManifestInvariants(): {
  valid: boolean;
  errors: string[];
  perContainer: { code: string; refs: number; pkgs: number; units: number }[];
  aggregate: { refs: number; pkgs: number; units: number };
} {
  const errors: string[] = [];
  const perContainer: { code: string; refs: number; pkgs: number; units: number }[] = [];

  let aggRefs = 0;
  let aggPkgs = 0;
  let aggUnits = 0;

  for (const spec of PLANNED_CONTAINERS) {
    const refs = spec.manifest.length;
    const pkgs = spec.manifest.reduce((s, r) => s + r.expectedPackages, 0);
    const units = spec.manifest.reduce((s, r) => s + r.expectedUnits, 0);

    perContainer.push({ code: spec.code, refs, pkgs, units });

    if (refs !== spec.totals.references) {
      errors.push(`${spec.code}: referencias=${refs}, esperado=${spec.totals.references}`);
    }
    if (pkgs !== spec.totals.expectedPackages) {
      errors.push(`${spec.code}: bultos=${pkgs}, esperado=${spec.totals.expectedPackages}`);
    }
    if (units !== spec.totals.expectedUnits) {
      errors.push(`${spec.code}: piezas=${units}, esperado=${spec.totals.expectedUnits}`);
    }

    const seen = new Set<string>();
    for (const r of spec.manifest) {
      const key = r.reference.trim().toUpperCase();
      if (seen.has(key)) {
        errors.push(`${spec.code}: referencia duplicada ${r.reference}`);
      }
      seen.add(key);
    }

    aggRefs += refs;
    aggPkgs += pkgs;
    aggUnits += units;
  }

  if (aggRefs !== PLANNED_AGGREGATE_TOTALS.references) {
    errors.push(`Total referencias=${aggRefs}, esperado=${PLANNED_AGGREGATE_TOTALS.references}`);
  }
  if (aggPkgs !== PLANNED_AGGREGATE_TOTALS.expectedPackages) {
    errors.push(`Total bultos=${aggPkgs}, esperado=${PLANNED_AGGREGATE_TOTALS.expectedPackages}`);
  }
  if (aggUnits !== PLANNED_AGGREGATE_TOTALS.expectedUnits) {
    errors.push(`Total piezas=${aggUnits}, esperado=${PLANNED_AGGREGATE_TOTALS.expectedUnits}`);
  }

  return {
    valid: errors.length === 0,
    errors,
    perContainer,
    aggregate: { refs: aggRefs, pkgs: aggPkgs, units: aggUnits },
  };
}
